package Basic;

public class variableBasic {
    static void main() {
        int x=5; // '/* */' used for multiline comment
        System.out.println(x+7); // '//' useed for one line comment
        x=9; // updation
        System.out.println(x); // special character can be used ex: only _ and $ not others
        int y; //declaration
        y=20; //initialize
        y=y+2;
        System.out.println(y); // build in name not work ex: if, else, int
        System.out.println("hi");//prints serially
        System.out.println(x*y); //no gap in variable name, don't start with number, but can contain number
    }
}
