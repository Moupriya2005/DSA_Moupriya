package Arrays;

public class ArrayOfOtherDataTypes {
    static void main() {
        char[] arr=new char[5];
        for(int i=0;i<5;i++){
            System.out.println(arr[i]+" ");
        }
        String[] arr1={"mou","priya","rup","sam","jack","suz"};
        for(int i=0;i<5;i++){
            System.out.println(arr1[i]+" ");
        }
    }
}
